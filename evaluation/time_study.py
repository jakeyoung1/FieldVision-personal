"""Minutes per finished report: by hand vs with FieldVision.

    .venv/bin/python -m evaluation.time_study                     # local files only
    FV_SCOUT_KEY=... .venv/bin/python -m evaluation.time_study --app-url URL   # pull the app's log first

Inputs
  time_study/hand_baseline.csv   one row per report a scout wrote the usual way,
                                 timed with a stopwatch (protocol: /methods#time)
  time_study/app_timings.csv     one row per report finished in FieldVision, as
                                 logged by the app (/api/timing/log): review
                                 seconds for that player, and the model wait

Rows still marked PLACEHOLDER are never counted. With no real rows on either
side, the script says there is no measurement instead of printing a number.
"""
import argparse
import csv
import json
import os
import statistics
import urllib.request
from pathlib import Path

HERE = Path(__file__).parent / "time_study"
HAND = HERE / "hand_baseline.csv"
APP = HERE / "app_timings.csv"
RESULTS = Path(__file__).parent / "results"

HAND_COLUMNS = ["player_id", "status", "scout", "date", "minutes", "pages_of_notes", "comment"]
APP_COLUMNS = ["id", "ts", "session_id", "player", "seconds_to_report", "seconds_to_finish", "finished_by"]


def _read(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def hand_minutes(rows: list[dict]) -> list[float]:
    out = []
    for r in rows:
        if r.get("status", "").strip().lower() != "measured":
            continue
        value = float(r["minutes"])
        if not 0 < value <= 240:
            raise ValueError(f"hand-written time {value} min is outside 0-240")
        out.append(value)
    return out


def app_minutes(rows: list[dict]) -> list[float]:
    """Minutes per FieldVision report: that player's review time plus the model wait.

    The app logs review time per player (report opened to reviewed) and the
    model wait per Analyze run. A batch shares one wait, but each report is
    charged the whole wait here. That overstates FieldVision's time for
    batches, which is the direction to err in when the claim is that it is faster.
    """
    return [(float(r["seconds_to_finish"]) + float(r.get("seconds_to_report") or 0)) / 60
            for r in rows if r.get("seconds_to_finish")]


def compare(hand: list[float], app: list[float]) -> dict:
    def side(xs):
        return {"reports": len(xs),
                "median_minutes": round(statistics.median(xs), 1) if xs else None,
                "minutes": [round(x, 1) for x in sorted(xs)]}
    h, a = side(hand), side(app)
    ratio = (round(a["median_minutes"] / h["median_minutes"], 2)
             if h["median_minutes"] and a["median_minutes"] else None)
    return {"by_hand": h, "fieldvision": a, "fieldvision_over_hand": ratio}


def pull(app_url: str) -> int:
    """Save the app's timing log to app_timings.csv."""
    req = urllib.request.Request(app_url.rstrip("/") + "/api/timing/log",
                                 headers={"X-Scout-Key": os.environ.get("FV_SCOUT_KEY", "")})
    with urllib.request.urlopen(req, timeout=30) as resp:
        rows = json.loads(resp.read())["rows"]
    with APP.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=APP_COLUMNS)
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in APP_COLUMNS})
    return len(rows)


def to_markdown(c: dict) -> str:
    h, a = c["by_hand"], c["fieldvision"]
    lines = ["# Time study: minutes per finished report", "",
             "Generated by `python -m evaluation.time_study`. Do not edit by hand.", ""]
    if not h["reports"] or not a["reports"]:
        lines += [f"**No measurement yet.** Hand-written reports timed: {h['reports']}. "
                  f"FieldVision reports timed: {a['reports']}. Both sides are needed before "
                  "anything can be compared. Protocol: /methods#time.", ""]
    else:
        lines += ["| | Reports | Median minutes |", "|---|---|---|",
                  f"| By hand | {h['reports']} | {h['median_minutes']} |",
                  f"| FieldVision | {a['reports']} | {a['median_minutes']} |", "",
                  f"FieldVision takes {c['fieldvision_over_hand']:.0%} of the hand-written time (median).",
                  "", f"All times, by hand: {h['minutes']}", f"All times, FieldVision: {a['minutes']}"]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--app-url", help="pull /api/timing/log from this deployment first")
    args = parser.parse_args()
    if args.app_url:
        print(f"pulled {pull(args.app_url)} timing rows")
    result = compare(hand_minutes(_read(HAND)), app_minutes(_read(APP)))
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "time_study.json").write_text(json.dumps(result, indent=2) + "\n")
    md = to_markdown(result)
    (RESULTS / "time_study.md").write_text(md + "\n")
    print(md)


if __name__ == "__main__":
    main()
